// Package digest builds .rsk/SKILLS.md, the one file the tool adapters import
// for a project's pinned skills. Each pinned skill contributes its DIGEST.md
// (a short list of always-on rules) instead of its whole SKILL.md body, and the
// file lives inside the project so Claude Code's @-import actually loads it.
package digest

import (
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"go.ralva.dev/ralvaskills/v3/internal"
	"go.ralva.dev/ralvaskills/v3/internal/fsx"
	"go.ralva.dev/ralvaskills/v3/internal/skill"
)

const (
	// FileName is the digest a skill ships beside its SKILL.md.
	FileName = "DIGEST.md"

	// IndexFileName is the generated file inside .rsk/ that the adapters import.
	IndexFileName = "SKILLS.md"

	// BudgetTokens is the estimated size above which the generated file is
	// considered too heavy for an always-loaded import.
	BudgetTokens = 2000

	bytesPerToken = 4
	tempPattern   = ".rsk-*.tmp"
	generatedNote = "<!-- Generated by rsk from the pinned skills' DIGEST.md. Do not edit; run `rsk pin` or `rsk update` to regenerate. -->"
)

// Entry is one pinned skill's contribution to the generated file.
type Entry struct {
	Name    string
	Version string
	Body    string
}

// Load reads the digest of the skill installed in dir. A skill without a
// DIGEST.md contributes a one-line entry built from its description, and a
// directory that does not exist (a pin that is not installed) says so.
func Load(dir, name string) Entry {
	entry := Entry{Name: name}
	fm, fmErr := skill.ReadFrontmatter(dir)
	if fmErr != nil {
		fm = skill.Frontmatter{} // unreadable or versionless SKILL.md: fall back to the bare name
	}
	entry.Version = fm.Version

	data, err := os.ReadFile(filepath.Join(dir, FileName))
	switch {
	case err == nil:
		entry.Body = demote(strings.TrimSpace(string(data)))
	case errors.Is(err, os.ErrNotExist) && fm.Description != "":
		entry.Body = "- " + name + ": " + fm.Description
	case errors.Is(err, os.ErrNotExist):
		entry.Body = "- " + name + " (no digest, and not readable here; is it installed?)"
	default:
		entry.Body = "- " + name + " (digest unreadable: " + err.Error() + ")"
	}
	return entry
}

// demote drops a leading H1 and pushes every other heading one level down, so
// a digest nests under its "## name" section. Digests carry no code fences.
func demote(body string) string {
	lines := strings.Split(body, "\n")
	out := make([]string, 0, len(lines))
	for i, line := range lines {
		switch {
		case i == 0 && strings.HasPrefix(line, "# "):
			continue
		case strings.HasPrefix(line, "#"):
			out = append(out, "#"+line)
		default:
			out = append(out, line)
		}
	}
	return strings.TrimSpace(strings.Join(out, "\n"))
}

// Render builds the file content for entries, in the given order.
func Render(entries []Entry) string {
	var b strings.Builder
	b.WriteString(generatedNote + "\n\n# Pinned skills\n")
	for _, e := range entries {
		heading := "## " + e.Name
		if e.Version != "" {
			heading += " v" + e.Version
		}
		b.WriteString("\n" + heading + "\n\n" + e.Body + "\n")
	}
	return b.String()
}

// EstimateTokens approximates the token count of s.
func EstimateTokens(s string) int {
	return (len(s) + bytesPerToken - 1) / bytesPerToken
}

// Sync writes .rsk/SKILLS.md in projectDir from the pinned skills installed in
// .claude/skills/, or removes it when nothing is pinned. It returns the
// estimated size of what it wrote.
func Sync(projectDir string, pinned []string) (int, error) {
	path := filepath.Join(projectDir, internal.ProjectFolderName, IndexFileName)
	if len(pinned) == 0 {
		if err := os.Remove(path); err != nil && !errors.Is(err, os.ErrNotExist) {
			return 0, fmt.Errorf("remove %s: %w", path, err)
		}
		return 0, nil
	}

	skillsDir := filepath.Join(projectDir, ".claude", skill.SkillsFolderName)
	entries := make([]Entry, 0, len(pinned))
	for _, name := range pinned {
		entries = append(entries, Load(filepath.Join(skillsDir, name), name))
	}
	content := Render(entries)

	if err := fsx.WriteAtomic(path, tempPattern, func(w io.Writer) error {
		_, err := io.WriteString(w, content)
		return err
	}); err != nil {
		return 0, fmt.Errorf("write %s: %w", path, err)
	}
	return EstimateTokens(content), nil
}
