"""Snapshot the roles this page uses from @ralvarez-ts/tokens.

The landing pages are single-file HTML with no CDN and no runtime dependency, so
they cannot import the package. They do not hand-copy it either: this script
reads ``tokens.css`` + ``sharp.css`` from an installed copy and writes
``tokens.json`` with the effective value of each role for both themes. The
metadata block lets ``--check`` fail the build when the package moves.

Usage:
    python3 tokens_extract.py /path/to/node_modules/@ralvarez-ts/tokens
    python3 tokens_extract.py /path/to/node_modules/@ralvarez-ts/tokens --check

The package is private (GitHub Packages), so the snapshot holds only the roles
the page consumes, not the package files.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

OUT = Path(__file__).with_name("tokens.json")

# Page role -> package custom property. Roles the package does not define
# (terminal TokyoNight, --info, the ink label on a cyan fill) are an rsk layer
# applied in family.py, not here.
ROLES = {
    "bg": "--color-bg",
    "bg2": "--color-surface",
    "surface": "--color-card",
    "line": "--color-border",
    "line-2": "--color-border-strong",
    "text": "--color-text",
    "muted": "--color-muted",
    "accent": "--color-accent-text",
    "accent-t": "--color-accent-text",
    "ok": "--color-success-text",
    "warn": "--color-warning-text",
    "danger": "--color-danger-text",
    "sel": "--color-accent-tint",
}
RADII = {"control": "--radius-control", "card": "--radius-card"}


def _blocks(css: str) -> dict[str, str]:
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    out: dict[str, str] = {}
    for m in re.finditer(r"([^{}]+)\{([^{}]*)\}", css):
        out[m.group(1).strip()] = m.group(2)
    return out


def _decls(body: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for part in body.split(";"):
        if ":" not in part:
            continue
        k, v = part.split(":", 1)
        k, v = k.strip(), v.strip()
        if k.startswith("--"):
            out[k] = v
    return out


def _pick(blocks: dict[str, str], *needles: str) -> dict[str, str]:
    """Merge every block whose selector contains all needles (in order)."""
    found = {}
    for sel, body in blocks.items():
        flat = re.sub(r"\s+", "", sel)
        if all(re.sub(r"\s+", "", n) in flat for n in needles):
            found.update(_decls(body))
    return found


def _exact(blocks: dict[str, str], selector: str) -> dict[str, str]:
    """Declarations of one block, matched by the whole selector."""
    want = re.sub(r"\s+", "", selector)
    for sel, body in blocks.items():
        if re.sub(r"\s+", "", sel) == want:
            return _decls(body)
    return {}


def read(pkg: Path) -> dict:
    pkg_json = json.loads((pkg / "package.json").read_text())
    src = pkg / "src"
    files = {name: (src / name).read_bytes() for name in ("tokens.css", "sharp.css")}
    base = _blocks(files["tokens.css"].decode())
    sharp = _blocks(files["sharp.css"].decode())

    base_dark = _decls(base.get("@theme static", ""))
    base_light = _exact(base, ':root[data-theme="light"]')
    sharp_shared = _exact(sharp, ':root[data-style="sharp"]')
    sharp_dark = _pick(sharp, ':root[data-style="sharp"]', ':not([data-theme="light"])')
    sharp_light = _pick(sharp, ':root[data-style="sharp"]', '[data-theme="light"]')

    dark = {**base_dark, **sharp_shared, **sharp_dark}
    light = {**base_dark, **base_light, **sharp_shared, **sharp_light}

    def roles(src_map: dict[str, str], theme: str) -> dict[str, str]:
        out = {}
        for role, prop in ROLES.items():
            if prop not in src_map:
                raise SystemExit(f"{theme}: {prop} missing from the package")
            out[role] = src_map[prop]
        return out

    return {
        "_meta": {
            "package": pkg_json["name"],
            "version": pkg_json["version"],
            "style": "sharp",
            "files": {n: hashlib.sha256(b).hexdigest() for n, b in files.items()},
            "note": (
                "Generated by tokens_extract.py from tokens.css + sharp.css. "
                "Only the roles this page uses; app-specific roles live in family.py."
            ),
        },
        "light": roles(light, "light"),
        "dark": roles(dark, "dark"),
        # The family landing pages hand-draw 4/6 px, the base ladder, not sharp's
        # zero geometry: a square console reads as an app, not a page. Both are
        # recorded so the choice is visible and checkable.
        "radii": {k: base_dark[v] for k, v in RADII.items()},
        "radii_sharp": {k: {**base_dark, **sharp_shared}[v] for k, v in RADII.items()},
    }


def main() -> None:
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    pkg = Path(sys.argv[1]).expanduser().resolve()
    snap = read(pkg)
    text = json.dumps(snap, indent=2, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            raise SystemExit(
                f"tokens.json is stale against {snap['_meta']['package']} "
                f"{snap['_meta']['version']} — re-run without --check"
            )
        print(f"tokens.json matches {snap['_meta']['package']} {snap['_meta']['version']}")
        return
    OUT.write_text(text)
    print(f"tokens.json <- {snap['_meta']['package']} {snap['_meta']['version']}")


if __name__ == "__main__":
    main()
